import { CalculateMetadataFunction, Composition, Still, staticFile } from "remotion";
import { ALL_FORMATS, Input, UrlSource } from "mediabunny";
import { Video, type VideoProps } from "./Video";
import { PianoThumbnail } from "./piano/Thumbnail";
import { PokerJacks, POKER_DURATION, POKER_FPS } from "./poker/PokerJacks";
import { PokerIvey, IVEY_DURATION, IVEY_FPS } from "./poker-ivey/PokerIvey";
import { PokerIvey2D } from "./poker-ivey/PokerIvey2D";
import { TwistDemo, DEMO_DURATION } from "./demo-twist/Demo";
import { DrumLevels, DRUM_LEVELS_DURATION, FPS as DRUM_FPS } from "./drums/DrumLevels";
import { DrumShort, DRUM_SHORT_DURATION } from "./drums/DrumShort";
import { PianoLevels, PIANO_LEVELS_DURATION, FPS as PIANO_FPS } from "./piano/PianoLevels";
import { TeleportUlt, TELEPORT_ULT_DURATION, FPS as REEL_FPS } from "./reels/teleport-ult/TeleportUlt";

const FPS = 30;
const DEFAULT_SECONDS = 12;
/** Extra time after the voiceover ends before the video ends. */
const TAIL_SECONDS = 1.5;

const defaultProps: VideoProps = {
  title: "Welcome to 3D",
  subtitle: "three.js + Remotion",
  // Generated by `npm run voiceover`. Set to null to use the demo captions/music only.
  voiceoverFile: "voiceover/voiceover.mp3",
  captionsFile: "voiceover/voiceover.captions.json",
  musicFile: "audio/music.mp3",
  accentColor: "#7c5cff",
};

/** When there's a voiceover, make the video exactly as long as the narration. */
const calculateMetadata: CalculateMetadataFunction<VideoProps> = async ({ props }) => {
  if (!props.voiceoverFile) {
    return { durationInFrames: FPS * DEFAULT_SECONDS };
  }
  const input = new Input({ formats: ALL_FORMATS, source: new UrlSource(staticFile(props.voiceoverFile)) });
  const seconds = await input.computeDuration();
  return { durationInFrames: Math.ceil((seconds + TAIL_SECONDS) * FPS) };
};

export const RemotionRoot: React.FC = () => {
  return (
    <>
      {/* ---- YouTube videos (16:9) ---- */}
      <Composition
        id="PianoLevels"
        component={PianoLevels}
        durationInFrames={PIANO_LEVELS_DURATION}
        fps={PIANO_FPS}
        width={1920}
        height={1080}
      />
      <Composition
        id="DrumLevels"
        component={DrumLevels}
        durationInFrames={DRUM_LEVELS_DURATION}
        fps={DRUM_FPS}
        width={1920}
        height={1080}
      />
      <Composition
        id="DrumLevels2D"
        component={DrumLevels}
        durationInFrames={DRUM_LEVELS_DURATION}
        fps={DRUM_FPS}
        width={1920}
        height={1080}
        defaultProps={{ look: "2d" as const }}
      />
      <Composition id="PokerJacks" component={PokerJacks} durationInFrames={POKER_DURATION} fps={POKER_FPS} width={1920} height={1080} />
      <Composition id="TwistDemo" component={TwistDemo} durationInFrames={DEMO_DURATION} fps={30} width={1080} height={1920} />
      <Composition id="PokerIvey2D" component={PokerIvey2D} durationInFrames={IVEY_DURATION} fps={IVEY_FPS} width={1920} height={1080} />
      <Composition id="PokerIvey" component={PokerIvey} durationInFrames={IVEY_DURATION} fps={IVEY_FPS} width={1920} height={1080} />
      <Still id="PianoThumbnail" component={PianoThumbnail} width={1280} height={720} />
      {/* ---- Reels (9:16) ---- */}
      <Composition id="Short-RobotDrummer" component={DrumShort} durationInFrames={DRUM_SHORT_DURATION} fps={DRUM_FPS} width={1080} height={1920} />
      <Composition id="Short-CartoonDrummer" component={DrumShort} durationInFrames={DRUM_SHORT_DURATION} fps={DRUM_FPS} width={1080} height={1920} defaultProps={{ look: "2d" as const }} />
      <Composition
        id="Reel-TeleportUlt"
        component={TeleportUlt}
        durationInFrames={TELEPORT_ULT_DURATION}
        fps={REEL_FPS}
        width={1080}
        height={1920}
      />

      {/* Landscape YouTube video */}
      <Composition
        id="Main3DVideo"
        component={Video}
        fps={FPS}
        width={1920}
        height={1080}
        defaultProps={defaultProps}
        calculateMetadata={calculateMetadata}
      />
      {/* Vertical YouTube Short */}
      <Composition
        id="Short3DVideo"
        component={Video}
        fps={FPS}
        width={1080}
        height={1920}
        defaultProps={defaultProps}
        calculateMetadata={calculateMetadata}
      />
    </>
  );
};
